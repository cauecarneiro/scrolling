export function svg(name, size = "1em", extra = "") {
  return `<svg class="icon ${extra}" viewBox="0 0 24 24" width="${size}" height="${size}" aria-hidden="true">${PATHS[name] || ""}</svg>`;
}

/** Troca todo <span data-icon="nome" data-size="16"> pelo SVG correspondente. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll("[data-icon]")) {
    el.innerHTML = svg(el.dataset.icon, el.dataset.size || "1em");
    el.style.display = "inline-flex";
    el.removeAttribute("data-icon");
  }
}
